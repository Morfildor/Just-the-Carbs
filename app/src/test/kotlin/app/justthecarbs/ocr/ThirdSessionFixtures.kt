/**
 * The nine labels photographed on a Samsung SM-S928B on 2026-09-01 (third phone session), as ML Kit
 * actually returned them.
 *
 * Every element text and every box below is **generated** from the `diagnostics.txt` of the evidence
 * bundle named above each function — `docs/Scan evidence 01-09-26 3rd testr/<id>/`. Nothing is
 * transcribed by hand, idealised, simplified, or re-spaced, and no element is omitted: the counts
 * here match the `elements=` line of each bundle exactly (97, 82, 92, 76, 92, 48, 157, 150, 179).
 *
 * ### Why these are documents and not strings
 *
 * Most of the failures these fixtures exist for are **geometric**: a column anchored on the wrong x,
 * a value bound to the column beside the one it was printed under, a per-100 span that swallowed the
 * neighbouring column's quantity. None of that is visible in row text alone, so a plain-text fixture
 * would pass while the device failed — the trap this repo has already recorded for the Dutch header
 * fixture and the soft-keyboard geometry test.
 *
 * ### Why the ingredient prose is kept
 *
 * [HardwareLabelFixtures] omits the non-table elements of its captures for readability. These do
 * not, and that turned out to matter: the ingredient blocks are what make
 * [UnitAccompanimentPolicy]'s document-level question answerable, they supply the percent clusters
 * [ColumnClassifier]'s cell fallback recovers columns from, and on the Korean sauce a row of
 * ingredients classifies as `CARBOHYDRATE_CHILD` (it names "brown sugar") and takes part in the
 * document's structure. A fixture without them measures a different document.
 *
 * ### Reading the coordinates
 *
 * The captures are 1684x3648 upright. Boxes are `[left, top, right, bottom]` in that space, so the
 * numbers here can be diffed directly against the evidence bundle's own element listing. ML Kit's
 * block and line ids are reproduced because the bundles record them and keeping them makes a fixture
 * checkable against its source; the row builder ignores them for membership.
 */
